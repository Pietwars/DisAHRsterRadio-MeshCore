#!/usr/bin/env python3
"""Bettet die Weboberflaeche (web/) in die Companion-Firmware ein (keine externen Ressourcen)."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
cr = root / 'examples/companion_radio'
html = (root / 'web/index.html').read_text(encoding='utf-8')
assert ')DRPAGE"' not in html
(cr / 'PortalPage.h').write_text('// Generated by tools/embed_web.py\n#pragma once\n#include <Arduino.h>\nstatic const char PORTAL_PAGE[] PROGMEM = R"DRPAGE(' + html + ')DRPAGE";\n', encoding='utf-8', newline='\n')
def arr(name, data): return 'static const uint8_t %s[] PROGMEM = {%s};\n' % (name, ','.join(str(b) for b in data))
man = (root / 'web/app.webmanifest').read_text(encoding='utf-8').strip()
out = '// Generated by tools/embed_web.py\n#pragma once\n#include <Arduino.h>\n'
out += 'static const char PORTAL_MANIFEST[] PROGMEM = R"ASSET(' + man + ')ASSET";\n'
out += arr('PORTAL_ICON', (root / 'web/app-icon.png').read_bytes())
out += '#define PORTAL_HAS_BG 1\n'
out += arr('PORTAL_BG_WEBP', (root / 'web/bg.webp').read_bytes())
maps = sorted((root / 'web/map').glob('*.json.gz'))
for m in maps: out += arr('MAP_' + m.name.split('.')[0].upper(), m.read_bytes())
out += 'struct PortalMap { const char *name; const uint8_t *data; size_t len; };\n'
out += 'static const PortalMap PORTAL_MAPS[] = {' + ','.join('{"%s",MAP_%s,sizeof(MAP_%s)}' % (m.name.split('.')[0], m.name.split('.')[0].upper(), m.name.split('.')[0].upper()) for m in maps) + '};\n'
(cr / 'PortalAssets.h').write_text(out, encoding='utf-8', newline='\n')
print('Seite %d Bytes, Bild %d Bytes, %d Karten (%d Bytes)' % (len(html.encode()), (root / 'web/bg.webp').stat().st_size, len(maps), sum(m.stat().st_size for m in maps)))
